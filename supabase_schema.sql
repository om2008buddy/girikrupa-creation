-- ===================================================================
-- GURUKRUPA CREATION - SUPABASE DATABASE SCHEMA
-- કુર્તી-પેન્ટ મેન્યુફેક્ચરિંગ નફા હિસાબ અને મેનેજમેન્ટ સિસ્ટમ
-- ===================================================================

-- 1. Merchants Table (વેપારી માસ્ટર)
CREATE TABLE IF NOT EXISTS merchants (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  phone TEXT,
  address TEXT,
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Designs Master (ડિઝાઇન કેટલોગ)
CREATE TABLE IF NOT EXISTS designs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  design_no TEXT NOT NULL UNIQUE,
  name TEXT,
  party_rate NUMERIC DEFAULT 0,
  karigar_kurti_rate NUMERIC DEFAULT 0,
  karigar_pant_rate NUMERIC DEFAULT 0,
  press_rate NUMERIC DEFAULT 0,
  material_cost NUMERIC DEFAULT 0,
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Inward Lots (વેપારી પાસેથી આવેલ માલ)
CREATE TABLE IF NOT EXISTS inward_lots (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lot_no TEXT,
  merchant_id BIGINT REFERENCES merchants(id) ON DELETE CASCADE,
  design_id BIGINT REFERENCES designs(id) ON DELETE CASCADE,
  date DATE NOT NULL DEFAULT CURRENT_DATE,
  total_pieces INTEGER NOT NULL DEFAULT 0,
  rate_per_piece NUMERIC NOT NULL DEFAULT 0,
  total_amount NUMERIC NOT NULL DEFAULT 0,
  fabric_details TEXT,
  status TEXT DEFAULT 'કામ ચાલુ છે',
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Karigars Master (કારીગર માસ્ટર)
CREATE TABLE IF NOT EXISTS karigars (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  phone TEXT,
  speciality TEXT DEFAULT 'સિલાઈ',
  address TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Karigar Work Entries (કારીગર કામ / પીસ બનાવ્યા)
CREATE TABLE IF NOT EXISTS karigar_work_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  karigar_id BIGINT REFERENCES karigars(id) ON DELETE CASCADE,
  lot_id BIGINT REFERENCES inward_lots(id) ON DELETE SET NULL,
  design_id BIGINT REFERENCES designs(id) ON DELETE CASCADE,
  date DATE NOT NULL DEFAULT CURRENT_DATE,
  kurti_pieces INTEGER DEFAULT 0,
  kurti_rate NUMERIC DEFAULT 0,
  pant_pieces INTEGER DEFAULT 0,
  pant_rate NUMERIC DEFAULT 0,
  other_pieces INTEGER DEFAULT 0,
  other_rate NUMERIC DEFAULT 0,
  other_label TEXT,
  total_amount NUMERIC NOT NULL DEFAULT 0,
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Karigar Upad / Advance (કારીગર ઉપાડ)
CREATE TABLE IF NOT EXISTS karigar_upad (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  karigar_id BIGINT REFERENCES karigars(id) ON DELETE CASCADE,
  date DATE NOT NULL DEFAULT CURRENT_DATE,
  amount NUMERIC NOT NULL DEFAULT 0,
  payment_mode TEXT DEFAULT 'રોકડ',
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. Press Vendors (પ્રેસ વાળા માસ્ટર)
CREATE TABLE IF NOT EXISTS press_vendors (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  phone TEXT,
  address TEXT,
  default_rate NUMERIC DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 8. Press Entries (પ્રેસ કામ એન્ટ્રી)
CREATE TABLE IF NOT EXISTS press_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vendor_id BIGINT REFERENCES press_vendors(id) ON DELETE CASCADE,
  lot_id BIGINT REFERENCES inward_lots(id) ON DELETE SET NULL,
  design_id BIGINT REFERENCES designs(id) ON DELETE SET NULL,
  date DATE NOT NULL DEFAULT CURRENT_DATE,
  pieces INTEGER NOT NULL DEFAULT 0,
  rate_per_piece NUMERIC NOT NULL DEFAULT 0,
  total_amount NUMERIC NOT NULL DEFAULT 0,
  status TEXT DEFAULT 'બાકી',
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 9. Raw Materials (મટીરીયલ્સ / કાચો માલ ખર્ચ)
CREATE TABLE IF NOT EXISTS materials (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  material_name TEXT NOT NULL,
  date DATE NOT NULL DEFAULT CURRENT_DATE,
  quantity NUMERIC NOT NULL DEFAULT 0,
  unit TEXT DEFAULT 'નંગ',
  rate NUMERIC NOT NULL DEFAULT 0,
  total_amount NUMERIC NOT NULL DEFAULT 0,
  supplier_name TEXT,
  bill_no TEXT,
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 10. Factory Expenses / Khata Kharch (કારખાના ખાતા ખર્ચ: ભાડું, લાઈટ, કચરો, પાણી, ચા-નાસ્તો)
CREATE TABLE IF NOT EXISTS factory_expenses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category TEXT NOT NULL,
  date DATE NOT NULL DEFAULT CURRENT_DATE,
  amount NUMERIC NOT NULL DEFAULT 0,
  paid_to TEXT,
  payment_mode TEXT DEFAULT 'રોકડ',
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 11. Fixed Staff Master (ફિક્સ પગાર સ્ટાફ)
CREATE TABLE IF NOT EXISTS fixed_staff (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  phone TEXT,
  role TEXT DEFAULT 'હેલ્પર',
  salary_type TEXT DEFAULT 'દૈનિક',
  base_rate NUMERIC NOT NULL DEFAULT 0,
  standard_hours NUMERIC DEFAULT 8,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 12. Staff Attendance & Hours (હાજરી અને કલાક રજિસ્ટર)
CREATE TABLE IF NOT EXISTS staff_attendance (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_id BIGINT REFERENCES fixed_staff(id) ON DELETE CASCADE,
  date DATE NOT NULL DEFAULT CURRENT_DATE,
  status TEXT DEFAULT 'હાજર',
  hours_worked NUMERIC DEFAULT 8,
  calculated_pay NUMERIC NOT NULL DEFAULT 0,
  advance_deduction NUMERIC DEFAULT 0,
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 13. Delivery Challans (વેપારી માલ ચલણ)
CREATE TABLE IF NOT EXISTS delivery_challans (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  challan_no TEXT NOT NULL UNIQUE,
  date DATE NOT NULL DEFAULT CURRENT_DATE,
  merchant_id BIGINT REFERENCES merchants(id) ON DELETE CASCADE,
  lot_id BIGINT REFERENCES inward_lots(id) ON DELETE SET NULL,
  items_json JSONB NOT NULL DEFAULT '[]'::jsonb,
  total_pieces INTEGER NOT NULL DEFAULT 0,
  grand_total NUMERIC NOT NULL DEFAULT 0,
  notes TEXT,
  status TEXT DEFAULT 'જમા કરાવેલ',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 14. App Settings
CREATE TABLE IF NOT EXISTS app_settings (
  key TEXT PRIMARY KEY,
  value TEXT
);

